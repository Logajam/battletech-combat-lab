pub fn is_inferno_bin(m: &Mech, bin: ItemId) -> bool {
    m.items[bin].name.to_uppercase().contains("INFERNO")
}

/// (location, bin) for every explosive ammo bin that hasn't exploded or been destroyed; inferno: Some(true/false)
/// keeps only inferno / non-inferno bins.
pub fn live_ammo_bins(mech: &Mech, inferno: Option<bool>) -> Vec<(String, ItemId)> {
    let destroyed: HashSet<ItemId> = mech.destroyed_slot_info.values().filter_map(|i| i.instance_id).collect();
    let mut seen: HashSet<ItemId> = HashSet::new();
    let mut bins = Vec::new();
    for (location, slots) in &mech.crits {
        for slot in slots {
            let Slot::Item(id) = slot else { continue };
            let it = &mech.items[*id];
            if it.category.as_deref() == Some("ammo") && it.is_explosive && !it.exploded && !seen.contains(id) && !destroyed.contains(id) {
                seen.insert(*id);
                if inferno.map_or(true, |w| is_inferno_bin(mech, *id) == w) {
                    bins.push((location.clone(), *id));
                }
            }
        }
    }
    bins
}

pub fn ammo_bin_damage_value(b: &Battle, u: UnitId, bin: ItemId) -> Option<i64> {
    let entry = ammo::weapon_entry_for_ammo(b, &b.units[u].items[bin].name)?;
    ammo::damage_per_shot(&entry)
}

/// The bin with the most destructive ammo per shot explodes (p.107); ties go to the bin with the most shots left, then
/// the controller's choice (stub).
pub fn choose_exploding_bin(b: &mut Battle, u: UnitId, bins: &[(String, ItemId)]) -> (String, ItemId) {
    let mut scored: Vec<(i64, f64, String, ItemId)> = Vec::new();
    let mut unknown: Vec<String> = Vec::new();
    for (location, bin) in bins {
        let mut dv = ammo_bin_damage_value(b, u, *bin);
        if dv.is_none() {
            unknown.push(b.units[u].items[*bin].name.clone());
            dv = Some(0);
        }
        let shots = b.units[u].items[*bin].shots_left.map_or(f64::INFINITY, |s| s as f64);
        scored.push((dv.unwrap(), shots, location.clone(), *bin));
    }
    let mut best = (scored[0].0, scored[0].1);
    for s in &scored[1..] {
        if (s.0, s.1) > best {
            best = (s.0, s.1);
        }
    }
    let tied: Vec<(String, ItemId)> = scored.iter().filter(|s| (s.0, s.1) == best).map(|s| (s.2.clone(), s.3)).collect();
    if !unknown.is_empty() || tied.len() > 1 {
        let named: Vec<(String, String)> = tied.iter().map(|(l, i)| (l.clone(), b.units[u].items[*i].name.clone())).collect();
        let side = b.units[u].side_name.clone().unwrap_or_default();
        let k = crate::stubs::stub_heat_explosion_bin(b, &side, &named, best.0, &unknown);
        return tied[k].clone();
    }
    tied[0].clone()
}

pub fn check_ammo_explosion(b: &mut Battle, u: UnitId, inferno: bool) -> bool {
    let level = b.units[u].current_heat;
    let tn = if inferno { inferno_avoid_tn(level) } else { ammo_avoid_tn(level) };
    let Some(mut tn) = tn else { return false };
    tn -= ms::technical_officer_bonus(&b.units[u]);
    let bins = live_ammo_bins(&b.units[u], Some(inferno));
    if bins.is_empty() {
        return false;
    }
    let name = b.units[u].side_name.clone().unwrap_or_default();
    let kind = if inferno { "inferno ammo" } else { "ammo" };
    let roll = b.roll_2d6();
    if roll >= tn {
        b.log(format!("  [Heat] {}: {} explosion avoid roll at heat {}: needs {}, rolled {} - avoided.", name, kind, level, tn, roll));
        return false;
    }
    let (location, bin) = choose_exploding_bin(b, u, &bins);
    let bin_name = b.units[u].items[bin].name.clone();
    b.log(format!("  [Heat] {}: {} explosion avoid roll at heat {}: needs {}, rolled {} - {} in {} EXPLODES.", name, kind, level, tn, roll, bin_name, location));
    destroy_bin_slots(&mut b.units[u], bin);
    b.units[u].items[bin].exploded = true;
    apply_explosion(b, u, bin, &location);
    if !inferno {
        return false;
    }
    let burn = ammo::inferno_heat(&b.units[u].items[bin]);
    b.units[u].current_heat += burn;
    let now = b.units[u].current_heat;
    b.log(format!("  [Heat] {}: inferno ammo burns - +{} heat at once -> {}.", name, burn, now));
    true
}

fn destroy_bin_slots(m: &mut Mech, bin: ItemId) {
    let name = m.items[bin].name.clone();
    for (location, slots) in m.crits.iter_mut() {
        for (i, slot) in slots.iter_mut().enumerate() {
            if matches!(slot, Slot::Item(x) if *x == bin) {
                m.destroyed_slot_info.insert((location.clone(), i), SlotInfo { name: name.clone(), instance_id: Some(bin) });
                *slot = Slot::name("DESTROYED");
            }
        }
    }
}

// ---- life support (p.107) --------------------------------------------------------------------------------------------
pub fn has_life_support_hit(m: &Mech) -> bool {
    m.destroyed_slot_info.values().any(|i| i.name == "Life Support")
}

pub fn life_support_hits(b: &mut Battle, u: UnitId) {
    if !has_life_support_hit(&b.units[u]) {
        return;
    }
    let torso = b.units[u].torso_cockpit;
    let table: &[(i64, i64)] = if torso { &TORSO_COCKPIT_LIFE_SUPPORT_HITS_BY_HEAT } else { &LIFE_SUPPORT_HITS_BY_HEAT };
    let hits = highest(table, b.units[u].current_heat).unwrap_or(0);
    if hits == 0 {
        return;
    }
    ms::pilot_hit(&mut b.units[u], hits, true);
    let m = &b.units[u];
    let line = format!(
        "  [Heat] {}: life support destroyed{}, heat {} - MechWarrior takes {} hit(s) ({}/6).",
        m.side_name.clone().unwrap_or_default(),
        if torso { " (torso-mounted cockpit)" } else { "" },
        m.current_heat,
        hits,
        m.pilot_hits
    );
    b.log(line);
    b.is_destroyed(u);
}

// ---- end phase: heat sinks ---------------------------------------------------------------------------------------------
pub fn max_movement_heat(mech: &Mech) -> i64 {
    let mut best = if ms::compute_running_mp(mech) > 0 {
        movement_heat(mech, "Run", ms::compute_running_mp(mech))
    } else if ms::compute_walk_mp(mech) > 0 {
        movement_heat(mech, "Walk", ms::compute_walk_mp(mech))
    } else {
        movement_heat(mech, "Stand Still", 0)
    };
    let jump = ms::compute_jump_mp(mech);
    if jump > 0 {
        best = best.max(movement_heat(mech, "Jump", jump));
    }
    best
}

/// Heat of every weapon that could fire next turn (ammo permitting; an Ultra / Rotary AC at its full rate of fire).
pub fn max_weapon_heat(b: &mut Battle, u: UnitId) -> i64 {
    let out = ammo::unavailable_weapons(&b.units[u]);
    let top_bombast = BOMBAST_KINDS.iter().map(|k| crate::weapon_profiles::bombast(k).2).max().unwrap();
    let mut total = 0;
    for w in get_weapons(&b.units[u]) {
        if out.contains(&w) {
            continue;
        }
        let heat = b.units[u].items[w].heat.unwrap_or(0);
        total += heat * max_shots(b, u, w) + if is_bombast(b, u, w) { top_bombast } else { 0 };
    }
    total
}

/// End Phase (p.103): with min_heat > 0, keep only as many heat sinks on as the mech can afford.
pub fn choose_heat_sink_deactivation(b: &mut Battle, u: UnitId, next_turn: Option<i64>) {
    let working = ms::working_heat_sinks(&b.units[u]);
    let wanted_off;
    if b.units[u].min_heat <= 0 || b.is_destroyed(u) {
        wanted_off = 0;
    } else {
        let weapons = max_weapon_heat(b, u);
        let m = &b.units[u];
        let potential = m.current_heat
            + max_movement_heat(m)
            + weapons
            + engine_heat_by_hits(m.engine_hits.min(2))
            + stealth_next_turn(&mut b.units[u]).iter().map(|k| equip::stealth_heat_of(k)).sum::<i64>()
            + if weapons != 0 { weapon_fire_surcharge(&b.units[u]) } else { 0 };
        let fixed_cooling = if b.units[u].partial_wing_active { 3 } else { 0 };
        let per_sink = ms::heat_sink_rate(&b.units[u]) + if equip::radical_planned(b, u, next_turn, false) { 1 } else { 0 };
        let keep_on = 0.max(working.min((potential - b.units[u].min_heat - fixed_cooling).div_euclid(per_sink)));
        wanted_off = working - keep_on;
    }
    if wanted_off != b.units[u].deactivated_heat_sinks {
        let m = &b.units[u];
        let line = format!(
            "  [End] {}: heat sinks switched off {} -> {} of {} (min_heat {}).",
            m.side_name.clone().unwrap_or_default(),
            m.deactivated_heat_sinks,
            wanted_off,
            working,
            m.min_heat
        );
        b.log(line);
    }
    b.units[u].deactivated_heat_sinks = wanted_off;
}

/// Stealth systems that will run next turn (as if not shut down).
fn stealth_next_turn(m: &mut Mech) -> Vec<&'static str> {
    let saved = m.shutdown;
    m.shutdown = false;
    let r = equip::active_stealth(m);
    m.shutdown = saved;
    r
}
