/// One mech's Heat Phase - steps 1-5. weapon_heat already includes any destroyed-radical surcharge.
pub fn resolve_heat_phase(b: &mut Battle, u: UnitId, weapon_heat: i64) {
    let name = b.units[u].side_name.clone().unwrap_or_default();
    let was_shut_down = b.units[u].shutdown;
    let eng = engine_heat(&b.units[u]);
    let stealth = equip::stealth_heat(&b.units[u]);
    let sinks = ms::compute_heat_dissipation(&b.units[u]);
    let water_bonus = crate::water::dissipation_bonus(b, u, None);
    let dissipation = sinks + water_bonus;
    let before = b.units[u].current_heat;
    let outside = OUTSIDE_HEAT_CAP.min(b.units[u].outside_heat.unwrap_or(0));
    b.units[u].outside_heat = Some(0);
    let cap = b.units[u].capacitor_heat;
    b.units[u].capacitor_heat = 0;
    let magma = crate::hazards::magma_heat(b, u);
    let taser = crate::advanced_weapons::taser_heat(&b.units[u]);
    let movement = b.units[u].movement_heat;
    let generated = movement + weapon_heat + eng + stealth + outside + cap + magma + taser;
    let (extra, how) = extra_cooling(b, u, before + generated - dissipation);
    let now = 0.max(before + generated - dissipation - extra);
    b.units[u].current_heat = now;
    let overflow = now - OVERFLOW_HEAT;
    let mut line = format!("  [Heat] {}: {} + movement {} + weapons {} + engine {}", name, before, movement, weapon_heat, eng);
    if stealth != 0 {
        line += &format!(" + stealth {}", stealth);
    }
    if outside != 0 {
        line += &format!(" + outside {}", outside);
    }
    if cap != 0 {
        line += &format!(" + capacitors {}", cap);
    }
    if magma != 0 {
        line += &format!(" + magma {}", magma);
    }
    if taser != 0 {
        line += &format!(" + Taser {}", taser);
    }
    line += &format!(" - sinks {}", sinks);
    if water_bonus != 0 {
        line += &format!(" - water {}", water_bonus);
    }
    if !how.is_empty() {
        line += &format!(" - {} {}", how, extra);
    }
    line += &format!(" -> {}", now);
    if overflow > 0 {
        line += &format!(" (overflow {})", overflow);
    }
    b.log(line);

    overheat_checks(b, u, was_shut_down);
    if b.is_destroyed(u) {
        return;
    }
    life_support_hits(b, u);
    if b.is_destroyed(u) {
        return;
    }
    resolve_consciousness_checks(b, u, "Heat Phase (life support)");
    apply_heat_effects(b, u);
}

pub fn extra_cooling(b: &mut Battle, u: UnitId, projected: i64) -> (i64, &'static str) {
    if b.units[u].shutdown {
        return (0, "");
    }
    if equip::radical_planned(b, u, None, true) {
        if equip::escalating_roll(b, u, "radical", "Radical heat sink system") {
            return (ms::active_heat_sinks(&b.units[u]), "radical heat sinks");
        }
        equip::destroy_system(b, u, "radical", "failed activation");
        return (0, "");
    }
    if projected > b.units[u].min_heat && !equip::unused_coolant_pods(&b.units[u]).is_empty() {
        let pod = equip::use_coolant_pod(b, u);
        let line = format!("    {}: {} triggered.", b.units[u].side_name.clone().unwrap_or_default(), b.units[u].items[pod].name);
        b.log(line);
        return (ms::active_heat_sinks(&b.units[u]), "coolant pod");
    }
    (0, "")
}

/// Step 5: MP, to-hit and TSM effects for the coming turn, off the current Heat Scale level.
pub fn apply_heat_effects(b: &mut Battle, u: UnitId) {
    let m = &mut b.units[u];
    m.heat_mp_penalty = mp_penalty_for(m.current_heat);
    m.heat_fire_modifier = fire_modifier_for(m.current_heat);
    m.tsm_active = m.has_tsm && equip::tsm_active_for(m, m.current_heat);
    if m.heat_mp_penalty != 0 || m.heat_fire_modifier != 0 || m.tsm_active {
        let line = format!(
            "  [Heat] {}: heat {} -> next turn -{} Walking MP, +{} to ranged attacks{}.",
            m.side_name.clone().unwrap_or_default(),
            m.current_heat,
            m.heat_mp_penalty,
            m.heat_fire_modifier,
            if m.tsm_active { ", TSM active (+2 Walking MP)" } else { "" }
        );
        b.log(line);
    }
}

fn overheat_checks(b: &mut Battle, u: UnitId, was_shut_down: bool) {
    if was_shut_down {
        try_restart(b, u);
    } else {
        check_shutdown(b, u);
    }
    let mut done = [threshold_reached(&SHUTDOWN_THRESHOLDS, b.units[u].current_heat), 0, 0]; // shutdown, ammo, inferno
    let mut inferno_blew = ammo_step(b, u, &mut done);
    while inferno_blew && !b.is_destroyed(u) {
        let level = b.units[u].current_heat;
        let reached = threshold_reached(&SHUTDOWN_THRESHOLDS, level);
        if !b.units[u].shutdown && reached > done[0] {
            let line = format!("  [Heat] {}: inferno heat crossed a new shutdown threshold - rolling again.", b.units[u].side_name.clone().unwrap_or_default());
            b.log(line);
            check_shutdown(b, u);
        }
        done[0] = done[0].max(reached);
        inferno_blew = ammo_step(b, u, &mut done);
    }
}

fn ammo_step(b: &mut Battle, u: UnitId, done: &mut [i64; 3]) -> bool {
    let level = b.units[u].current_heat;
    if threshold_reached(&AMMO_THRESHOLDS, level) > done[1] {
        done[1] = threshold_reached(&AMMO_THRESHOLDS, level);
        check_ammo_explosion(b, u, false);
        if b.is_destroyed(u) {
            return false;
        }
        resolve_consciousness_checks(b, u, "Heat Phase (ammo explosion)");
    }
    if threshold_reached(&INFERNO_THRESHOLDS, level) > done[2] {
        done[2] = threshold_reached(&INFERNO_THRESHOLDS, level);
        let blew = check_ammo_explosion(b, u, true);
        if b.is_destroyed(u) {
            return false;
        }
        resolve_consciousness_checks(b, u, "Heat Phase (inferno explosion)");
        return blew;
    }
    false
}

pub fn check_shutdown(b: &mut Battle, u: UnitId) {
    let level = b.units[u].current_heat;
    let name = b.units[u].side_name.clone().unwrap_or_default();
    if level >= SHUTDOWN_AUTOMATIC_HEAT {
        shut_down(b, u, &format!("heat {} (30+: automatic)", level));
        return;
    }
    let Some(mut tn) = shutdown_avoid_tn(level) else { return };
    tn -= ms::technical_officer_bonus(&b.units[u]);
    if ms::pilot_unconscious(&b.units[u]) {
        shut_down(b, u, &format!("heat {}, MechWarrior unconscious - can't override", level));
        return;
    }
    let roll = b.roll_2d6();
    if roll >= tn {
        b.log(format!("  [Heat] {}: shutdown avoid roll at heat {}: needs {}, rolled {} - avoided.", name, level, tn, roll));
    } else {
        shut_down(b, u, &format!("heat {}, shutdown avoid roll needs {}, rolled {}", level, tn, roll));
    }
}

fn shut_down(b: &mut Battle, u: UnitId, why: &str) {
    b.units[u].shutdown = true;
    let line = format!("  [Heat] {}: SHUT DOWN ({}).", b.units[u].side_name.clone().unwrap_or_default(), why);
    b.log(line);
}

pub fn try_restart(b: &mut Battle, u: UnitId) {
    let level = b.units[u].current_heat;
    let name = b.units[u].side_name.clone().unwrap_or_default();
    if crate::advanced_weapons::held_down(&b.units[u]) {
        b.log(format!("  [Heat] {}: shut down by a Taser - no restart before the effect ends (TO:AUE p.158).", name));
        return;
    }
    let Some(tn) = shutdown_avoid_tn(level) else {
        b.units[u].shutdown = false;
        b.log(format!("  [Heat] {}: heat {} is below 14 - power plant restarts automatically.", name, level));
        return;
    };
    if level > RESTART_MAX_HEAT {
        b.log(format!("  [Heat] {}: heat {} - must be below 30 to restart; stays shut down.", name, level));
        return;
    }
    if ms::pilot_unconscious(&b.units[u]) {
        b.log(format!("  [Heat] {}: MechWarrior unconscious - no restart attempt at heat {}; stays shut down.", name, level));
        return;
    }
    let roll = b.roll_2d6();
    if roll >= tn {
        b.units[u].shutdown = false;
        b.log(format!("  [Heat] {}: restart roll at heat {}: needs {}, rolled {} - RESTARTED.", name, level, tn, roll));
    } else {
        b.log(format!("  [Heat] {}: restart roll at heat {}: needs {}, rolled {} - stays shut down.", name, level, tn, roll));
    }
}

