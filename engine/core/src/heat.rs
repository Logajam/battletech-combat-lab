pub const MP_PENALTY_BY_HEAT: [(i64, i64); 5] = [(25, 5), (20, 4), (15, 3), (10, 2), (5, 1)];
pub const FIRE_MODIFIER_BY_HEAT: [(i64, i64); 4] = [(24, 4), (17, 3), (13, 2), (8, 1)];
pub const SHUTDOWN_AVOID_BY_HEAT: [(i64, i64); 4] = [(26, 10), (22, 8), (18, 6), (14, 4)];
pub const SHUTDOWN_AUTOMATIC_HEAT: i64 = 30;
pub const RESTART_MAX_HEAT: i64 = 29;
pub const AMMO_AVOID_BY_HEAT: [(i64, i64); 3] = [(28, 8), (23, 6), (19, 4)];
pub const LIFE_SUPPORT_HITS_BY_HEAT: [(i64, i64); 2] = [(20, 2), (10, 1)];
pub const OVERFLOW_HEAT: i64 = 30;
pub const OUTSIDE_HEAT_CAP: i64 = 15;
pub const INFERNO_AVOID_BY_HEAT: [(i64, i64); 5] = [(28, 12), (23, 10), (19, 8), (14, 6), (10, 4)];
pub const INFERNO_HEAT_PER_MISSILE: i64 = 2;
pub const INFERNO_MAX_HEAT: i64 = 30;
pub const TORSO_COCKPIT_LIFE_SUPPORT_HITS_BY_HEAT: [(i64, i64); 2] = [(15, 2), (1, 1)];
pub const WALK_HEAT: i64 = 1;
pub const RUN_HEAT: i64 = 2;
pub const JUMP_MIN_HEAT: i64 = 3;
pub const XXL_JUMP_MIN_HEAT: i64 = 6;
pub const RADICAL_DESTROYED_EXTRA_HEAT: i64 = 1;

pub fn engine_heat_by_hits(hits: i64) -> i64 {
    match hits {
        0 => 0,
        1 => 5,
        2 => 10,
        other => panic!("KeyError: {}", other),
    }
}

fn highest(table: &[(i64, i64)], level: i64) -> Option<i64> {
    table.iter().find(|(t, _)| level >= *t).map(|(_, v)| *v)
}

const SHUTDOWN_THRESHOLDS: [i64; 5] = [30, 26, 22, 18, 14];
const AMMO_THRESHOLDS: [i64; 3] = [28, 23, 19];
const INFERNO_THRESHOLDS: [i64; 5] = [28, 23, 19, 14, 10];

fn threshold_reached(thresholds: &[i64], level: i64) -> i64 {
    thresholds.iter().find(|t| level >= **t).copied().unwrap_or(0)
}

pub fn mp_penalty_for(level: i64) -> i64 {
    highest(&MP_PENALTY_BY_HEAT, level).unwrap_or(0)
}
pub fn fire_modifier_for(level: i64) -> i64 {
    highest(&FIRE_MODIFIER_BY_HEAT, level).unwrap_or(0)
}
pub fn shutdown_avoid_tn(level: i64) -> Option<i64> {
    highest(&SHUTDOWN_AVOID_BY_HEAT, level)
}
pub fn ammo_avoid_tn(level: i64) -> Option<i64> {
    highest(&AMMO_AVOID_BY_HEAT, level)
}
pub fn inferno_avoid_tn(level: i64) -> Option<i64> {
    highest(&INFERNO_AVOID_BY_HEAT, level)
}

// ---- mech heat traits -------------------------------------------------------------------------------------------
fn is_ijj(name: &str) -> bool {
    name.replace(' ', "").replace('-', "").to_uppercase().contains("IMPROVEDJUMPJET")
}

pub fn has_improved_jump_jets(mech: &Mech) -> bool {
    for slots in mech.crits.values() {
        for s in slots {
            let name = match s {
                Slot::Name(n) => n.as_str(),
                Slot::Item(i) => mech.items[*i].name.as_str(),
            };
            if is_ijj(name) {
                return true;
            }
        }
    }
    mech.destroyed_slot_info.values().any(|i| is_ijj(&i.name))
}

pub fn has_xxl_engine(mech: &Mech) -> bool {
    mech.engine_desc.as_deref().unwrap_or("").to_uppercase().contains("XXL")
}

pub fn has_supercooled_myomer(mech: &Mech) -> bool {
    mech.myomer.replace(' ', "").replace('-', "").to_uppercase().contains("SUPERCOOLED")
}

/// Called once per battle per mech by the orchestrator.
pub fn attach_heat_traits(b: &mut Battle, u: UnitId) {
    let m = &b.units[u];
    let (ijj, xxl, sc) = (has_improved_jump_jets(m), has_xxl_engine(m), has_supercooled_myomer(m));
    let m = &mut b.units[u];
    m.has_improved_jump_jets = ijj;
    m.has_xxl_engine = xxl;
    m.has_supercooled_myomer = sc;
    equip::attach_equipment(b, u);
}

// ---- heat generated -----------------------------------------------------------------------------------------------
/// Heat generated by one turn's movement (p.102).
pub fn movement_heat(mech: &Mech, mode: &str, hexes_moved: i64) -> i64 {
    let extra = if mode != "Stand Still" && equip::radical_destroyed(mech) { RADICAL_DESTROYED_EXTRA_HEAT } else { 0 };
    let ijj = mech.has_improved_jump_jets;
    let xxl = mech.has_xxl_engine;
    if mode == "Jump" {
        if xxl && !ijj {
            return extra + XXL_JUMP_MIN_HEAT.max(2 * hexes_moved);
        }
        if ijj && !xxl {
            return extra + JUMP_MIN_HEAT.max(-((-hexes_moved).div_euclid(2)));
        }
        return extra + JUMP_MIN_HEAT.max(hexes_moved);
    }
    if mech.has_supercooled_myomer {
        return extra;
    }
    if xxl {
        return extra
            + match mode {
                "Stand Still" => 2,
                "Walk" => 4,
                "Run" => 6,
                other => panic!("KeyError: {}", other),
            };
    }
    extra + match mode {
        "Walk" => WALK_HEAT,
        "Run" => RUN_HEAT,
        _ => 0,
    }
}

/// Heat from engine critical hits this turn (p.102); none while shut down.
pub fn engine_heat(mech: &Mech) -> i64 {
    if mech.shutdown {
        return 0;
    }
    engine_heat_by_hits(mech.engine_hits.min(2))
}

pub fn weapon_fire_surcharge(mech: &Mech) -> i64 {
    if equip::radical_destroyed(mech) { RADICAL_DESTROYED_EXTRA_HEAT } else { 0 }
}

pub fn planned_cooling(b: &mut Battle, u: UnitId) -> i64 {
    if equip::radical_planned(b, u, None, false) { ms::active_heat_sinks(&b.units[u]) } else { 0 }
}

/// Heat this turn besides movement and weapons, net of planned extra cooling. Can be negative.
pub fn other_heat(b: &mut Battle, u: UnitId) -> i64 {
    let m = &b.units[u];
    let base = engine_heat(m) + equip::stealth_heat(m) + weapon_fire_surcharge(m);
    base - planned_cooling(b, u)
}

pub fn weapon_heat_budget(b: &mut Battle, u: UnitId, move_heat: i64) -> i64 {
    let m = &b.units[u];
    let head = m.max_heat + ms::compute_heat_dissipation(m) + crate::water::dissipation_bonus(b, u, None) - m.current_heat - move_heat;
    0.max(head - other_heat(b, u))
}

