"""
INTEGRATION__heat.py  (NEW 2026-10-18, Claude - Pile 2)

Heat rules shared by movement scoring (INTEGRATION__ranged_combat) and the
turn loop (INTEGRATION__orchestrator). Moved here out of the orchestrator so
ranged_combat can use them without a circular import. Rules are Daniel's,
2026-10-18:

  - Movement heat: Walk 1, Run 2, Jump max(3, hexes jumped) - with Improved
    Jump Jets max(3, ceil(hexes jumped / 2)). Stand Still 0.
  - Weapon heat budget per turn = max_heat + dissipation - current heat -
    movement heat (floored at 0): max_heat caps the end-of-turn heat level.
  - Heat is saved state: current_heat carries over turn to turn
    (accumulation itself happens in orchestrator._phase_heat).
"""

import math

from mech_state import compute_heat_dissipation

WALK_HEAT = 1
RUN_HEAT = 2
JUMP_MIN_HEAT = 3


def has_improved_jump_jets(mech):
    """True if any crit slot (live or already destroyed) is an Improved Jump
    Jet. Checks bare strings too: with the mini equipment DB, 'IS Improved
    Jump Jet' isn't in equipment.json, so the parser leaves it as a plain
    string instead of an Equipment instance."""
    def is_ijj(name):
        return "IMPROVEDJUMPJET" in name.replace(" ", "").replace("-", "").upper()
    for slots in mech.crits.values():
        for s in slots:
            name = s if isinstance(s, str) else getattr(s, "name", "")
            if is_ijj(name):
                return True
    return any(is_ijj(info["name"]) for info in mech.destroyed_slot_info.values())


def improved_jump_jets(mech):
    """Cached per mech: the orchestrator sets mech.has_improved_jump_jets once
    per battle; fall back to scanning if it hasn't."""
    flag = getattr(mech, "has_improved_jump_jets", None)
    if flag is None:
        flag = has_improved_jump_jets(mech)
        mech.has_improved_jump_jets = flag
    return flag


def movement_heat(mode, hexes_moved, improved_jj):
    """Heat generated by one turn's movement. hexes_moved for a jump is the
    straight-line hexes jumped (the jump's forward count from
    combat.build_jump_states)."""
    if mode == "Walk":
        return WALK_HEAT
    if mode == "Run":
        return RUN_HEAT
    if mode == "Jump":
        jumped = math.ceil(hexes_moved / 2) if improved_jj else hexes_moved
        return max(JUMP_MIN_HEAT, jumped)
    return 0  # Stand Still


def weapon_heat_budget(mech, move_heat):
    """max_heat + dissipation - current heat - movement heat, floored at 0.
    Same formula weapon_selection.select_weapons_to_fire applies internally;
    exposed here for logging."""
    return max(0, mech.max_heat + compute_heat_dissipation(mech) - mech.current_heat - move_heat)
